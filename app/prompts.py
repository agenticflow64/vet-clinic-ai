def format_price_context(items: list[dict]) -> str:
    lines = []
    for i, s in enumerate(items, 1):
        price = f"{s['price']} руб." if s["price"] else "уточняется"
        lines.append(f"{i}. [{s['category']}] {s['name']} — {price}")
    return "\n".join(lines)


def format_history(history: list[dict]) -> str:
    if not history:
        return "(пусто)"
    roles = {"user": "Пользователь", "assistant": "Ассистент"}
    return "\n".join(
        f"{roles.get(m['role'], m['role'])}: {m['content']}" for m in history
    )
