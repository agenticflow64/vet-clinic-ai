DEFAULT_CATEGORY = "Прочее"


def _norm(s: str) -> str:
    return " ".join(str(s).lower().split())


def _match(marker, text: str) -> bool:
    if isinstance(marker, re.Pattern):
        return marker.search(text) is not None
    return marker in text


def categorize(name: str) -> str:
    """Возвращает категорию для названия услуги.

    Сначала проверяются специфичные правила, затем хирургические маркеры,
    затем общая терапия; если ничего не подошло — «Прочее».
    """
    n = _norm(name)
    for category, markers in CATEGORY_RULES:
        for m in markers:
            if _match(m, n):
                return category
    for m in SURGERY_MARKERS:
        if _match(m, n):
            return "Хирургия"
    return DEFAULT_CATEGORY
