def test_known_services():
    for name, expected in CASES:
        got = categorize(name)
        assert got == expected, f"{name!r}: ожидалось {expected!r}, получено {got!r}"


def test_unknown_service_goes_to_misc():
    assert categorize("Ветлаб") == "Прочее"


def test_normalization_ignores_case_and_spaces():
    assert categorize("  КАСТРАЦИЯ   КОТА ") == "Хирургия"


def test_convert_produces_valid_records(tmp_path):
    """Скрипт конвертации: полный xlsx не трогаем, проверяем convert() на словарях."""
    from scripts.convert_pricelist import convert

    # convert работает с файлами; для юнит-проверки достаточно правил выше,
    # а здесь — что json в репо валиден и категории заполнены
    import json
    from pathlib import Path

    services = json.loads(
        (Path(__file__).parent.parent / "data" / "services.json").read_text(encoding="utf-8")
    )
    assert len(services) > 290, "полный прайс должен попасть в датасет"
    for s in services:
        assert s["category"], f"у {s['name']!r} нет категории"
        assert isinstance(s["price"], int) or s["price"] is None
    # записи с уникальными id
    ids = [s["id"] for s in services]
    assert len(ids) == len(set(ids))
